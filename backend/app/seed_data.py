def seed_database(conn):
    cursor = conn.cursor()
    
    # Check if professionals already exist
    cursor.execute("SELECT count(*) as cnt FROM professionals")
    existing_count = cursor.fetchone()["cnt"]
    if existing_count == 0:
        for p in SAMPLE_PROFESSIONALS:
            cursor.execute("""
            INSERT INTO professionals (
                id, name, category, skills, locality, latitude, longitude,
                rating, completed_jobs, response_time_min, is_available,
                price_range, profile_desc, avatar_url, phone, languages
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                p["id"],
                p["name"],
                p["category"],
                json.dumps(p["skills"]),
                p["locality"],
                p["latitude"],
                p["longitude"],
                p["rating"],
                p["completed_jobs"],
                p["response_time_min"],
                p["is_available"],
                p["price_range"],
                p["profile_desc"],
                p["avatar_url"],
                p["phone"],
                p["languages"]
            ))
        conn.commit()

    # Seed past requests if none exist
    cursor.execute("SELECT count(*) as cnt FROM service_requests")
    req_count = cursor.fetchone()["cnt"]
    if req_count == 0:
        for r in SAMPLE_PAST_REQUESTS:
            created_dt = (datetime.now(timezone.utc) - timedelta(days=r["days_ago"])).strftime("%Y-%m-%d %H:%M:%S")
            updated_dt = (datetime.now(timezone.utc) - timedelta(days=r["days_ago"], minutes=-45)).strftime("%Y-%m-%d %H:%M:%S")
            
            cursor.execute("""
            INSERT INTO service_requests (
                id, problem_description, raw_transcript, category, urgency,
                symptoms, safety_concerns, immediate_guidance, customer_location,
                customer_name, customer_phone, preferred_time, estimated_complexity,
                technician_briefing, assigned_professional_id, status,
                price_estimate_min, price_estimate_max, final_amount,
                timeline, notes, created_at, updated_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                r["id"],
                r["problem_description"],
                r["raw_transcript"],
                r["category"],
                r["urgency"],
                json.dumps(r["symptoms"]),
                r["safety_concerns"],
                r["immediate_guidance"],
                r["customer_location"],
                r["customer_name"],
                r["customer_phone"],
                r["preferred_time"],
                r["estimated_complexity"],
                r["technician_briefing"],
                r["assigned_professional_id"],
                r["status"],
                r["price_estimate_min"],
                r["price_estimate_max"],
                r["final_amount"],
                json.dumps(r["timeline"]),
                r["notes"],
                created_dt,
                updated_dt
            ))
        conn.commit()
